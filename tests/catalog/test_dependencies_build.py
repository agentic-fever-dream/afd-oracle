"""Tests for the dependencies-build catalogue family (one planted repo per group of builders)."""
from __future__ import annotations

CI = """name: CI
on: [push]
jobs:
  test:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Run tests
        run: pytest
"""
CI_WEAK = CI + "        continue-on-error: true\n"
CACHE = "name: cache\non: [push]\njobs:\n  b:\n    runs-on: ubuntu-latest\n    steps:\n      - uses: actions/cache@v4\n" \
        "        with:\n          path: ~/.cache/pip\n          key: pip-v{n}-linux\n"
GEN = "# Code generated by openapi-generator. DO NOT EDIT.\n# source: api/openapi.yaml\n\nclass Client:\n" \
      "    base = 'http://x'\n    retries = 3\n    timeout = 10\n"


def _build_repo(mini):
    r = mini()
    r.commit({
        "requirements.txt": "requests>=2.0\nflask>=2.0\nleftpad>=1\npytest>=7\n",
        "app.py": "import requests\n\n\ndef go():\n    return requests.get('x')\n",
        "Dockerfile": "FROM python:3.11-alpine\nRUN pip install -r requirements.txt\n",
        ".github/workflows/ci.yml": CI,
        ".github/workflows/nightly.yml": CI,
        ".github/workflows/cache.yml": CACHE.format(n=1),
        "Makefile": "CFLAGS = -O2 -Wall\n",
        "pkg/version.py": '__version__ = "1.0.0"\n',
        "pyproject.toml": '[project]\nname = "pkg"\nversion = "1.0.0"\n',
        "setup.cfg": "[metadata]\nname = pkg\nversion = 1.0.0\n",
        "api/openapi.yaml": "openapi: 3.0.0\n",
        "gen/client.py": GEN,
        "third_party/libfoo/README": "foo\n",
        **{f"third_party/libfoo/f{i}.c": f"int f{i}(void) {{ return {i}; }}\n" for i in range(11)},
    }, "Initial import", days=0)
    out = {}
    req = ["requests<2.30", "flask<3", "leftpad<2", "pytest>=7"]
    out["pin"] = r.commit({"requirements.txt": "requests<2.30\nflask>=2.0\nleftpad>=1\npytest>=7\n"},
                          "Pin requests: 2.30 breaks our adapter", days=10)
    r.commit({"requirements.txt": "requests<2.30\nflask<3\nleftpad>=1\npytest>=7\n"}, "Bump flask", days=11, author="bot")
    r.commit({"requirements.txt": "\n".join(req) + "\n"}, "tidy", days=12)
    r.commit({"requirements.txt": "\n".join(req + ["django==3.2.0"]) + "\n"}, "Add django", days=15)
    out["up"] = r.commit({"requirements.txt": "\n".join(req + ["django==4.0.0"]) + "\n"}, "Upgrade django", days=20)
    r.commit({"requirements.txt": "\n".join(req + ["django==4.0.0", "ujson==5.0.0", "black==23.1"]) + "\n",
              "app.py": "import requests\nimport ujson\n\n\ndef go():\n    return requests.get('x')\n"},
             "Add ujson for speed", days=25)
    out["p1"] = r.commit({"third_party/libfoo/f1.c": "int f1(void) { return 100; /* local patch */ }\n"},
                         "Patch libfoo overflow", days=26)
    out["p2"] = r.commit({"third_party/libfoo/f2.c": "int f2(void) { return 200; /* local patch two */ }\n"},
                         "Patch libfoo again", days=27)
    out["down"] = r.commit({"requirements.txt": "\n".join(req + ["django==3.2.0", "ujson==5.0.0", "black==23.1"]) + "\n"},
                           "Downgrade django, 4.0 breaks admin", days=30)
    out["hand"] = r.commit({"gen/client.py": GEN.replace("retries = 3", "retries = 5  # manual fix")},
                           "Fix retries in generated client manually", days=31)
    out["rm"] = r.commit({"requirements.txt": "\n".join(req + ["django==3.2.0"]) + "\n"},
                         "Remove ujson: conflicts with alpine build", days=35)
    r.commit({"pkg/version.py": '__version__ = "1.1.0"\n', "pyproject.toml": '[project]\nname = "pkg"\nversion = "1.1.0"\n',
              "setup.cfg": "[metadata]\nname = pkg\nversion = 1.1.0\n"}, "Release 1.1.0", days=40)
    out["flag_add"] = r.commit({"Makefile": "CFLAGS = -O2 -Wall -Werror\n"}, "Enable -Werror", days=45)
    out["slim"] = r.commit({"Dockerfile": "FROM python:3.11-slim\nRUN pip install -r requirements.txt\n"}, "Switch to slim", days=50)
    out["flag_rm"] = r.commit({"Makefile": "CFLAGS = -O2 -Wall\n"}, "Drop -Werror: gcc 13 miscompile", days=55)
    out["alpine"] = r.commit({"Dockerfile": "FROM python:3.11-alpine\nRUN pip install -r requirements.txt\n"},
                             "Revert to alpine", days=60)
    out["gate"] = r.commit({".github/workflows/ci.yml": CI_WEAK}, "Temporarily unblock CI, flaky tests", days=70)
    r.commit({".github/workflows/nightly.yml": CI_WEAK}, "nightly can fail", days=71)
    out["rel"] = r.commit({"pkg/version.py": '__version__ = "1.2.0"\n',
                           "pyproject.toml": '[project]\nname = "pkg"\nversion = "1.2.0"\n'}, "Release 1.2.0", days=80)
    r.commit({"setup.cfg": "[metadata]\nname = pkg\nversion = 1.2.0\n"}, "Fix version in setup.cfg", days=81)
    out["c2"] = r.commit({".github/workflows/cache.yml": CACHE.format(n=2)}, "bust cache", days=85)
    r.commit({"gen/client.py": GEN, "api/openapi.yaml": "openapi: 3.0.1\n"}, "Regenerate client", days=90)
    out["c3"] = r.commit({".github/workflows/cache.yml": CACHE.format(n=3)}, "bust cache again", days=95)
    out["rv"] = r.commit({f"third_party/libfoo/f{i}.c": f"int f{i}(void) {{ return {i}; }}\n/* v2 */\n" for i in range(11)},
                         "Update libfoo to 2.0", days=100)
    return r, out


def test_dependencies_and_build_family(mini):
    r, c = _build_repo(mini)
    r.ingest()

    hits = r.run("pinned_dependency_with_reason")
    subs = " ".join(h.subject for h in hits)
    assert any(h.subject.startswith("requirements.txt|requests|") and h.commits == [c["pin"]] for h in hits), subs
    assert "|flask|" not in subs and "|leftpad|" not in subs
    assert r.ctx.noise["pinned_dependency_with_reason/bot_bump"] >= 1
    assert r.ctx.noise["pinned_dependency_with_reason/no_stated_reason"] >= 1

    hits = r.run("ci_gate_weakening")
    assert [h.commits for h in hits] == [[c["gate"]]], [h.subject for h in hits]
    assert r.ctx.noise["ci_gate_weakening/nightly_or_experimental"] >= 1

    hits = r.run("dockerfile_base_image_aftermath")
    assert len(hits) == 1 and hits[0].commits[0] == c["slim"] and c["alpine"] in hits[0].commits

    hits = r.run("dependency_downgrade_or_revert")
    assert [h.commits for h in hits if "|django|" in h.subject] == [[c["up"], c["down"]]]

    hits = r.run("generated_code_hand_edited")
    assert [h.commits[0] for h in hits] == [c["hand"]]
    assert hits[0].evidence["manual_lines_lost_in_regeneration"] >= 1
    assert r.ctx.noise["generated_code_hand_edited/pure_regeneration"] >= 1

    hits = r.run("vendored_copy_local_patch")
    assert len(hits) == 1 and hits[0].subject == "third_party/libfoo"
    assert c["rv"] in hits[0].commits and hits[0].evidence["lines_lost_in_revendor"] >= 2

    hits = r.run("version_literal_multifile_sync_lag")
    assert len(hits) == 1 and hits[0].commits[0] == c["rel"] and hits[0].evidence["version"] == "1.2.0"
    assert "setup.cfg" in hits[0].evidence["missed_then_repaired"]

    hits = r.run("dependency_adopt_then_remove")
    assert [h.title.split()[0] for h in hits] == ["ujson"]
    assert hits[0].commits[1] == c["rm"]
    assert r.ctx.noise["dependency_adopt_then_remove/dev_tool"] >= 1

    hits = r.run("build_flag_toggle_churn")
    assert [h.subject for h in hits] == ["Makefile|-Werror"] and c["flag_rm"] in hits[0].commits

    hits = r.run("cache_key_design_and_bust_churn")
    assert len(hits) == 1 and {c["c2"], c["c3"]} <= set(hits[0].commits)


def test_monkeypatch_dependency_bump_overlap(mini):
    r = mini()
    r.commit({"requirements.txt": "requests==2.28.0\n",
              "app/patches.py": "import requests\nimport requests.adapters\n\nrequests.adapters.DEFAULT_RETRIES = 7\n",
              "app/other.py": "import requests\n\nrequests.sessions.Session.timeout = 3\n"}, "Add retry tuning", days=0)
    r.commit({"requirements.txt": "requests==2.29.0\n"}, "Update requests", days=20)
    r.commit({"requirements.txt": "requests==2.31.0\n"}, "Update requests again", days=40)
    r.commit({"app/other.py": "import requests\n\nrequests.sessions.Session.timeout = 4\n"}, "tune timeout", days=60)
    r.commit({"tests/test_p.py": "import requests\n\nrequests.adapters.DEFAULT_RETRIES = 1\n"}, "test patch", days=61)
    hits = r.run("monkeypatch_dependency_bump_overlap")
    assert [h.paths for h in hits] == [["app/patches.py"]]
    assert len(hits[0].evidence["bumps_after"]) == 2
    assert r.ctx.noise["monkeypatch_dependency_bump_overlap/patch_edited_after_latest_bump"] >= 1


# ---- upgraded builders: lockfile history (grep_aux), blame (line_origins), vendored lines (grep_aux) ---------
def _poetry(ver: str, extra: str = "") -> str:
    return ('[[package]]\nname = "requests"\nversion = "' + ver + '"\ndescription = "HTTP"\n\n'
            '[[package]]\nname = "idna"\nversion = "3.4"\ndescription = "names"\n' + extra)


def test_monkeypatch_bump_overlap_reads_lockfile_history_from_aux(mini):
    r = mini()
    r.commit({"pyproject.toml": '[project]\nname = "x"\ndependencies = ["requests>=2"]\n',
              "poetry.lock": _poetry("2.28.0"),
              "app/patches.py": "import requests\nimport requests.adapters\n\nrequests.adapters.DEFAULT_RETRIES = 7\n"},
             "Add retry tuning", days=0)
    r.commit({"poetry.lock": _poetry("2.29.0")}, "lock: requests 2.29", days=20)
    # a brand-new package in the lockfile is not a bump of requests
    r.commit({"poetry.lock": _poetry("2.29.0", '\n[[package]]\nname = "urllib3"\nversion = "2.0.0"\n')}, "lock: add urllib3", days=30)
    r.commit({"poetry.lock": _poetry("2.31.0", '\n[[package]]\nname = "urllib3"\nversion = "2.0.0"\n')}, "lock: requests 2.31", days=40)
    ctx = r.ingest()
    assert ctx.grep_aux(r'version = "2\.31\.0"'), "lockfile lines must be in the aux index (ignored by core ingestion)"
    assert not ctx.grep(r'version = "2\.31\.0"')
    hits = r.run("monkeypatch_dependency_bump_overlap")
    assert [h.paths for h in hits] == [["app/patches.py"]]
    assert hits[0].evidence["package"] == "requests"
    assert len(hits[0].evidence["bumps_after"]) == 2  # 2.29 and 2.31; the urllib3 addition is not a requests bump


def test_monkeypatch_bump_overlap_npm_lockfile(mini):
    r = mini()
    lock = lambda v: ('{\n  "name": "app",\n  "packages": {\n    "node_modules/axios": {\n      "version": "%s",\n'
                      '      "resolved": "x"\n    }\n  }\n}\n' % v)
    r.commit({"package.json": '{\n  "name": "app",\n  "dependencies": {\n    "axios": "^1.0.0"\n  }\n}\n', "package-lock.json": lock("1.1.0"),
              "src/patch.js": "const axios = require('axios')\n\naxios.defaults.maxRedirects = 2\n"}, "patch axios", days=0)
    r.commit({"package-lock.json": lock("1.2.0")}, "bump axios lock", days=15)
    hits = r.run("monkeypatch_dependency_bump_overlap")
    assert len(hits) == 1 and hits[0].evidence["package"] == "axios" and len(hits[0].evidence["bumps_after"]) == 1


def test_vendored_patch_loss_from_aux_lines(mini):
    r = mini()
    files = {f"vendor/libbar/f{i}.c": f"int f{i}(void) {{ return {i}; }}\n" for i in range(11)}
    r.commit(files, "Vendor libbar", days=0)
    r.commit({"vendor/libbar/f1.c": "int f1(void) { return 100; /* local patch */ }\n"}, "Patch libbar", days=5)
    r.commit({"vendor/libbar/f2.c": "int f2(void) { return 200; /* local patch two */ }\n"}, "Patch libbar again", days=6)
    rv = r.commit({f"vendor/libbar/f{i}.c": f"int f{i}(void) {{ return {i}; }}\n/* v2 */\n" for i in range(11)},
                  "Update libbar", days=20)
    ctx = r.ingest()
    assert ctx.grep_aux("local patch", "+", "vendor/%")
    hits = r.run("vendored_copy_local_patch")
    assert len(hits) == 1 and rv in hits[0].commits and hits[0].evidence["lines_lost_in_revendor"] >= 2
